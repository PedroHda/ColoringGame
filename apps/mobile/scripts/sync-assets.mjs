import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";
import "./sync-clothing.mjs";
const app = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const root = path.resolve(app, "../..");
const { optimizeIllustrations } = await import(
  pathToFileURL(path.join(root, "scripts/optimize-illustrations.mjs")).href
);
const report = await optimizeIllustrations({
  out: path.join(app, "assets/illustrations"),
  thumbnails: true,
});
const masterEntries = report.files
  .map(
    (file) =>
      `  '/illustrations/${file.file}': require('../../assets/illustrations/${file.file}'),`,
  )
  .join("\n");
const thumbnailEntries = report.files
  .filter((file) => file.thumbnail)
  .map(
    (file) =>
      `  '/illustrations/${file.file}': require('../../assets/illustrations/${file.thumbnail.file}'),`,
  )
  .join("\n");
await mkdir(path.join(app, "src/generated"), { recursive: true });
await writeFile(
  path.join(app, "src/generated/illustrations.ts"),
  `// Generated by npm run assets from validated, lossless distribution files.\nexport const illustrationAssets: Record<string, number> = {\n${masterEntries}\n};\nexport const illustrationThumbnails: Record<string, number> = {\n${thumbnailEntries}\n};\n`,
);
console.log(
  `Mobile: ${report.files.length} ilustrações reais offline; ${report.originalBytes} → ${report.bytes} bytes sem alterar pixels. Miniaturas: ${report.thumbnailBytes} bytes.`,
);
